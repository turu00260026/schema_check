/**
 * update_kanji.cjs
 * 各学年のJSONの問題文を、その学年で習う漢字に書き直す
 *
 * 2年生で使える漢字（1年+2年生習得済み）:
 *   何、同、数、多、少、長、計、算、正、答、図、入、食、作、台、書 など
 *   ※ 全(3年)、倍(3年)、式(3年)、面(3年)は2年生問題では使わない
 *
 * 3年生で追加できる漢字（+3年生）:
 *   式、全、部、倍、等、短、配、箱、動、始、終、集、物、重、乗、問、題、場、面 など
 */

const fs = require('fs');
const path = require('path');

// ────────────────────────────────────────────
// 置換ルール定義
// 順序に注意：長いパターンを先に処理する
// ────────────────────────────────────────────

// 2年生・3年生共通（1年+2年の漢字で書ける）
const COMMON_RULES = [
  // 疑問詞（なんにん と なん人 の両パターンに対応）
  [/なんにん/g, '何人'],
  [/なん人/g, '何人'],
  [/なんびき/g, '何びき'],
  [/なんだい/g, '何台'],
  [/なんまい/g, '何まい'],
  [/なんきゃく/g, '何きゃく'],
  [/なんcm/g, '何cm'],
  [/なんこ/g, '何こ'],
  [/なん本/g, '何本'],
  [/なん箱/g, '何箱'],
  // 形容詞（長 は2年生）
  [/ながい/g, '長い'],
  // 状況
  [/おなじかずの まとまり/g, '同じ数の まとまり'],
  [/おなじかず/g, '同じ数'],
  [/どちらが おおい/g, 'どちらが 多い'],
  [/どちらがおおい/g, 'どちらが多い'],
  // 動詞
  [/はいっています/g, '入っています'],
  [/はいって/g, '入って'],
  // 計算
  [/けいさんすれば/g, '計算すれば'],
  [/けいさんは/g, '計算は'],
  [/けいさんを/g, '計算を'],
  // 正しい (正は1年生)
  [/どのひっ算が ただしい/g, 'どのひっ算が 正しい'],
  [/どれが ただしい/g, 'どれが 正しい'],
  [/ただしい/g, '正しい'],
  // 答え (答は2年生)
  [/こたえ/g, '答え'],
];

// 3年生のみ（3年生で習う漢字を追加で使う）
const GRADE3_RULES = [
  // 式 (3年)
  [/しきは どれですか？/g, '式は どれですか？'],
  [/しきは どれ？/g, '式は どれ？'],
  [/ただしい しきを/g, '正しい式を'],
  // 全部 (全・部ともに3年)
  [/ぜんぶで/g, '全部で'],
  [/ぜんぶ/g, '全部'],
  // 何倍 (倍は3年)
  [/なんばいか/g, '何倍か'],
  [/なんばい/g, '何倍'],
  // 問題 (問・題ともに3年)
  [/この もんだいでは/g, 'この問題では'],
  [/この もんだいに/g, 'この問題に'],
  [/この もんだいは/g, 'この問題は'],
  [/もんだいでは/g, '問題では'],
  [/もんだいに/g, '問題に'],
  [/もんだいは/g, '問題は'],
  [/もんだいを/g, '問題を'],
  [/もんだい/g, '問題'],
  // 場面 (場は2年・面は3年)
  [/ばめん/g, '場面'],
  // 短い (短は3年)
  [/みじかい/g, '短い'],
  // 分ける (分は2年、2年でも使える→grade3ではより積極的に)
  [/わけますか/g, '分けますか'],
  [/わけかたですか/g, '分け方ですか'],
  [/わけかたは/g, '分け方は'],
  [/わけかた/g, '分け方'],
  [/わけると/g, '分けると'],
  [/わけると/g, '分けると'],
  [/わけて/g, '分けて'],
  [/わけた/g, '分けた'],
  [/わける/g, '分ける'],
  // 数ずつ (数は2年)
  [/かずずつ/g, '数ずつ'],
  // 配る (配は3年)
  [/くばれますか/g, '配れますか'],
  [/くばれて/g, '配れて'],
  [/くばると/g, '配ると'],
  [/くばり/g, '配り'],
  [/くばる/g, '配る'],
  // 求める (求は小学校範囲外→使わない)
  // 倍（倍は3年）— 数字+ばい・何ばい のパターンすべて
  [/何ばい/g, '何倍'],
  [/(\d+)ばい/g, '$1倍'],
  // 等分 (等は3年)  ※write_grade3.cjsでは既に等分と書いている箇所あり→そのまま
  // 箱 (箱は3年) ただし ふくろ(袋)は範囲外→そのまま
  [/はこに/g, '箱に'],
  [/はこが/g, '箱が'],
  [/はこを/g, '箱を'],
  [/はこ /g, '箱 '],
  [/はこ。/g, '箱。'],
  [/はこ？/g, '箱？'],
  // 短い (短は3年)はGRADE3_RULESに既にあり
];

// ────────────────────────────────────────────
// 置換実行
// ────────────────────────────────────────────
function applyRules(text, rules) {
  let result = text;
  for (const [pattern, replacement] of rules) {
    result = result.replace(pattern, replacement);
  }
  return result;
}

function updateGrade(filename, extraRules = []) {
  const filePath = path.join(__dirname, 'src', 'data', 'questions', filename);
  const original = fs.readFileSync(filePath, 'utf8');
  let updated = applyRules(original, COMMON_RULES);
  if (extraRules.length > 0) {
    updated = applyRules(updated, extraRules);
  }
  fs.writeFileSync(filePath, updated, 'utf8');
  console.log(`✅ ${filename} を更新しました`);
}

updateGrade('grade2.json');
updateGrade('grade3.json', GRADE3_RULES);

console.log('\n完了。ビルドして確認してください。');
