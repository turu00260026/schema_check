// ユーザーターン。日付と「最近使った場面」を渡して重複を避ける。
export function buildUserPrompt({ dateLabel, recent, seed }) {
  const lines = [`今日は${dateLabel}です。`];
  if (recent.length) {
    lines.push("", "最近の手紙で使った場面と一手（かぶらせないこと）：");
    for (const r of recent) lines.push(`- ${r.day}｜${r.scene}｜${r.request}`);
  }
  lines.push(
    "",
    `乱数：${seed}（同じ日でも別の手紙を書くための種。内容には書かない）`,
    "",
    "今日の手紙を1通、JSONで。",
  );
  return lines.join("\n");
}
